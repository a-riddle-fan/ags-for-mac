    public enum CompletionKind
    {
        Keyword,
        Type,
        Function,
        Variable,
        EnumValue,
        Define,
    }

    public sealed class CompletionItem
    {
        public CompletionItem(string text, CompletionKind kind, string description)
        {
            Text = text;
            Kind = kind;
            Description = description;
        }

        public string Text { get; }
        public CompletionKind Kind { get; }
        public string Description { get; }

        public override string ToString() => Text;
    }

    /// <summary>
    /// Script autocomplete built on upstream's parser (AutoComplete.ConstructCache → ScriptAutoCompleteData).
    /// The scripts visible to a script are, as in the upstream editor: the built-in API (agsdefns.sh),
    /// the generated _AutoGenerated.ash (characters, inventory, GUIs, …), the module headers above it
    /// in compile order, and the script itself.
    /// </summary>
    public sealed class ScriptCompletion
    {
        private static readonly Regex Identifier = new Regex(@"[A-Za-z_][A-Za-z0-9_]*$");
        private readonly Game _game;
        private readonly Script _builtIn;
        private Script _autoGenerated;
        private Script _globalVariables;

        public ScriptCompletion(Game game)
        {
            _game = game ?? throw new ArgumentNullException(nameof(game));
            using (var reader = new StreamReader(EditorResources.Open("agsdefns.sh")))
                _builtIn = new Script("agsdefns.sh", reader.ReadToEnd(), true);
            AutoComplete.ConstructCache(_builtIn, null);
            RefreshGeneratedHeader();
        }

        /// <summary>Rebuilds _AutoGenerated.ash after items were added, removed or renamed.</summary>
        public void RefreshGeneratedHeader()
        {
            _autoGenerated = new AutoGeneratedHeader().RegenerateScriptHeader(_game, null);
            AutoComplete.ConstructCache(_autoGenerated, new[] { _builtIn });
            _globalVariables = new Script("_GlobalVariables.ash", GlobalVariablesHeader(_game), true);
            AutoComplete.ConstructCache(_globalVariables, null);
        }

        /// <summary>GlobalVariablesComponent.UpdateScriptHeader: imports of all global variables.</summary>
        public static string GlobalVariablesHeader(Game game)
        {
            var sb = new System.Text.StringBuilder();
            foreach (GlobalVariable variable in game.GlobalVariables.ToList())
            {
                switch (variable.ArrayType)
                {
                    case GlobalVariableArrayType.None:
                        sb.AppendLine($"import {variable.Type} {variable.Name};");
                        break;
                    case GlobalVariableArrayType.Array:
                        sb.AppendLine($"import {variable.Type} {variable.Name}[{variable.ArraySize}];");
                        break;
                    case GlobalVariableArrayType.DynamicArray:
                        sb.AppendLine($"import {variable.Type} {variable.Name}[];");
                        break;
                }
            }
            return sb.ToString();
        }

        /// <summary>Headers a script can see (upstream AGSEditor.GetImportedScriptHeaders).</summary>
        public List<Script> GetImportedHeaders(Script script)
        {
            var result = new List<Script> { _builtIn, _autoGenerated, _globalVariables };
            foreach (ScriptAndHeader module in _game.RootScriptFolder.AllItemsFlat)
            {
                if (module.Header == script || module.Script == script)
                {
                    if (module.Script == script)
                        result.Add(module.Header); // a script sees its own header
                    break;
                }
                result.Add(module.Header);
            }
            return result;
        }

        /// <summary>Parses the current text of a script (call before asking for completions).</summary>
        public void Update(Script script)
        {
            List<Script> imports = GetImportedHeaders(script);
            foreach (Script header in imports.Skip(3))
                if (!header.AutoCompleteData.Populated)
                    AutoComplete.ConstructCache(header, imports.TakeWhile(h => h != header));
            AutoComplete.ConstructCache(script, imports);
        }

        private IEnumerable<ScriptAutoCompleteData> Visible(Script script) =>
            GetImportedHeaders(script).Append(script).Select(s => s.AutoCompleteData).Where(d => d != null);

        /// <summary>
        /// Members for "expression." at <paramref name="offset"/> (just after the dot). Static members for
        /// type names (e.g. "Game."), instance members for variables (e.g. "player.", "cDave.").
        /// </summary>
        public IReadOnlyList<CompletionItem> GetMembers(Script script, string text, int offset)
        {
            int dot = offset - 1;
            if (dot < 0 || text[dot] != '.') return Array.Empty<CompletionItem>();
            var data = Visible(script).ToList();
            ScriptStruct type = ParsePreviousExpression(data, text, dot, out bool staticAccess);
            if (type == null) return Array.Empty<CompletionItem>();

            var items = new List<CompletionItem>();
            var seen = new HashSet<string>();
            for (ScriptStruct s = type; s != null; s = string.IsNullOrEmpty(s.ParentType) ? null : FindStruct(data, s.ParentType))
            {
                bool inherited = s != type;
                foreach (ScriptFunction f in s.Functions)
                {
                    if (f.IsProtected || (inherited && f.NoInherit) || !ShouldShowThis(f)) continue;
                    if (staticAccess ? !(f.IsStatic || f.IsStaticOnly) : f.IsStaticOnly) continue;
                    if (seen.Add(f.FunctionName))
                        items.Add(new CompletionItem(f.FunctionName, CompletionKind.Function, $"{f.Type} {s.Name}.{f.FunctionName}({f.ParamList})"));
                }
                foreach (ScriptVariable v in s.Variables)
                {
                    if (v.IsProtected || (inherited && v.NoInherit) || !ShouldShowThis(v)) continue;
                    if (staticAccess ? !(v.IsStatic || v.IsStaticOnly) : v.IsStaticOnly) continue;
                    if (seen.Add(v.VariableName))
                        items.Add(new CompletionItem(v.VariableName, CompletionKind.Variable, $"{v.Type}{(v.IsPointer ? "*" : "")} {s.Name}.{v.VariableName}{(v.IsArray ? "[]" : "")}"));
                }
            }
            return items.OrderBy(i => i.Text, StringComparer.OrdinalIgnoreCase).ToList();
        }

        /// <summary>Global identifiers starting with <paramref name="prefix"/> (case-insensitive).</summary>
        public IReadOnlyList<CompletionItem> GetGlobal(Script script, string prefix)
        {
            prefix ??= string.Empty;
            bool Matches(string name) => name != null && name.StartsWith(prefix, StringComparison.OrdinalIgnoreCase);
            var items = new Dictionary<string, CompletionItem>();
            void Add(CompletionItem item)
            {
                if (Matches(item.Text) && !items.ContainsKey(item.Text))
                    items.Add(item.Text, item);
            }

            foreach (ScriptAutoCompleteData d in Visible(script))
            {
                foreach (ScriptFunction f in d.Functions)
                    if (!f.HideOnMainFunctionList && ShouldShowThis(f))
                        Add(new CompletionItem(f.FunctionName, CompletionKind.Function, $"{f.Type} {f.FunctionName}({f.ParamList})"));
                foreach (ScriptVariable v in d.Variables.Where(ShouldShowThis))
                    Add(new CompletionItem(v.VariableName, CompletionKind.Variable, $"{v.Type}{(v.IsPointer ? "*" : "")} {v.VariableName}"));
                foreach (ScriptStruct s in d.Structs.Where(ShouldShowThis))
                    Add(new CompletionItem(s.Name, CompletionKind.Type, "struct " + s.Name));
                foreach (ScriptEnum e in d.Enums.Where(ShouldShowThis))
                {
                    Add(new CompletionItem(e.Name, CompletionKind.Type, "enum " + e.Name));
                    foreach (ScriptEnumValue v in e.EnumValues)
                        Add(new CompletionItem(v.Name, CompletionKind.EnumValue, $"{e.Name}.{v.Name}"));
                }
                foreach (ScriptDefine def in d.Defines)
                    Add(new CompletionItem(def.Name, CompletionKind.Define, "#define " + def.Name));
            }
            foreach (string keyword in Constants.SCRIPT_KEY_WORDS.Split(' ', StringSplitOptions.RemoveEmptyEntries))
                Add(new CompletionItem(keyword, CompletionKind.Keyword, "keyword"));

            return items.Values.OrderBy(i => i.Text, StringComparer.OrdinalIgnoreCase).ToList();
        }

        // ScintillaWrapper.ShouldShowThis (upstream): hides API entries that the game's settings
        // exclude through #ifdef/#ifndef (STRICT, STRICT_STRINGS, STRICT_AUDIO, API/compat versions, …).
        private bool ShouldShowThis(ScriptToken token)
        {
            Settings gameSettings = _game.Settings;
            if ((token.IfNDefOnly == "STRICT") && (gameSettings.EnforceObjectBasedScript)) return false;
            if ((token.IfDefOnly == "STRICT") && (!gameSettings.EnforceObjectBasedScript)) return false;
            if ((token.IfNDefOnly == "STRICT_STRINGS") && (gameSettings.EnforceNewStrings)) return false;
            if ((token.IfDefOnly == "STRICT_STRINGS") && (!gameSettings.EnforceNewStrings)) return false;
            if ((token.IfNDefOnly == "STRICT_AUDIO") && (gameSettings.EnforceNewAudio)) return false;
            if ((token.IfDefOnly == "STRICT_AUDIO") && (!gameSettings.EnforceNewAudio)) return false;
            if ((token.IfNDefOnly == "NEW_DIALOGOPTS_API") && (!gameSettings.UseOldCustomDialogOptionsAPI)) return false;
            if ((token.IfDefOnly == "NEW_DIALOGOPTS_API") && (gameSettings.UseOldCustomDialogOptionsAPI)) return false;
            if ((token.IfNDefOnly == "NEW_KEYINPUT_API") && (!gameSettings.UseOldKeyboardHandling)) return false;
            if ((token.IfDefOnly == "NEW_KEYINPUT_API") && (gameSettings.UseOldKeyboardHandling)) return false;
            if (token.IfNDefOnly != null && token.IfNDefOnly.StartsWith("SCRIPT_API_"))
            {
                ScriptAPIVersion? v = ParseApiVersion(token.IfNDefOnly.Substring("SCRIPT_API_".Length));
                if (v.HasValue && v <= gameSettings.ScriptAPIVersionReal) return false;
            }
            if (token.IfDefOnly != null && token.IfDefOnly.StartsWith("SCRIPT_API_"))
            {
                ScriptAPIVersion? v = ParseApiVersion(token.IfDefOnly.Substring("SCRIPT_API_".Length));
                if (v.HasValue && v > gameSettings.ScriptAPIVersionReal) return false;
            }
            if (token.IfNDefOnly != null && token.IfNDefOnly.StartsWith("SCRIPT_COMPAT_"))
            {
                ScriptAPIVersion? v = ParseApiVersion(token.IfNDefOnly.Substring("SCRIPT_COMPAT_".Length));
                if (v.HasValue && v >= gameSettings.ScriptCompatLevelReal) return false;
            }
            if (token.IfDefOnly != null && token.IfDefOnly.StartsWith("SCRIPT_COMPAT_"))
            {
                ScriptAPIVersion? v = ParseApiVersion(token.IfDefOnly.Substring("SCRIPT_COMPAT_".Length));
                if (v.HasValue && v < gameSettings.ScriptCompatLevelReal) return false;
            }
            return true;
        }

        /// <summary>A function calltip (upstream ConstructFunctionCalltipText) and the parameter being typed.</summary>
        public sealed class CallTip
        {
            public CallTip(string prefix, IReadOnlyList<string> parameters, int currentParameter, string description, IReadOnlyList<string> enumValues)
            {
                Prefix = prefix; Parameters = parameters; CurrentParameter = currentParameter; Description = description; EnumValues = enumValues;
            }
            /// <summary>"Type Struct.Name(" — the parameters follow, then ")".</summary>
            public string Prefix { get; }
            /// <summary>Parameters as upstream shows them ("optional " for parameters with defaults).</summary>
            public IReadOnlyList<string> Parameters { get; }
            /// <summary>Index of the parameter at the caret (may be past the last one).</summary>
            public int CurrentParameter { get; }
            public string Description { get; }
            /// <summary>When the current parameter is an enum: its values (upstream shows them instead of the calltip).</summary>
            public IReadOnlyList<string> EnumValues { get; }
            public string Text => Prefix + string.Join(", ", Parameters) + ")";
        }

        /// <summary>
        /// The calltip for the call the caret is in (upstream ScintillaWrapper.ShowFunctionCalltip): the innermost
        /// unclosed '(' before <paramref name="offset"/>, the function before it (global or "x.Member"), and the
        /// index of the argument being typed. Null outside calls or for unknown functions.
        /// </summary>
        public CallTip GetCallTip(Script script, string text, int offset)
        {
            if (string.IsNullOrEmpty(text) || offset <= 0 || offset > text.Length) return null;
            // Mark string/char literals and comments up to the caret so their brackets and commas are ignored.
            int scanFrom = Math.Max(0, text.LastIndexOf("\nfunction ", Math.Max(0, offset - 1), StringComparison.Ordinal));
            var code = new bool[offset];
            for (int i = scanFrom; i < offset; i++)
            {
                char c = text[i];
                if (c == '"' || c == '\'')
                {
                    code[i] = false;
                    char quote = c;
                    for (i++; i < offset && text[i] != quote && text[i] != '\n'; i++)
                        if (text[i] == '\\') i++;
                    continue;
                }
                if (c == '/' && i + 1 < offset && text[i + 1] == '/')
                {
                    while (i < offset && text[i] != '\n') i++;
                    continue;
                }
                code[i] = true;
            }

            int depth = 0, commas = 0, open = -1;
            for (int i = offset - 1; i >= scanFrom; i--)
            {
                if (!code[i]) continue;
                char c = text[i];
                if (c == ')' || c == ']') depth++;
                else if (c == '[') { if (depth == 0) return null; depth--; }
                else if (c == '(')
                {
                    if (depth == 0) { open = i; break; }
                    depth--;
                }
                else if (c == ',' && depth == 0) commas++;
                else if ((c == ';' || c == '{' || c == '}') && depth == 0) return null;
            }
            if (open < 0) return null;

            int nameEnd = open;
            while (nameEnd > 0 && char.IsWhiteSpace(text[nameEnd - 1])) nameEnd--;
            Match nameMatch = Identifier.Match(text.Substring(0, nameEnd));
            if (!nameMatch.Success) return null;
            string name = nameMatch.Value;

            Update(script);
            var data = Visible(script).ToList();
            ScriptFunction func = null;
            ScriptStruct owner = null;
            int nameStart = nameMatch.Index;
            if (nameStart > 0 && text[nameStart - 1] == '.')
            {
                Match m = Identifier.Match(text.Substring(0, nameStart - 1));
                if (!m.Success) return null;
                ScriptStruct type = FindStruct(data, m.Value);
                if (type == null)
                {
                    string typeName = FindVariableType(data, m.Value) ?? FindLocalVariableType(text, m.Index, m.Value);
                    type = typeName == null ? null : FindStruct(data, typeName);
                }
                for (ScriptStruct s = type; s != null && func == null; s = string.IsNullOrEmpty(s.ParentType) ? null : FindStruct(data, s.ParentType))
                {
                    func = s.FindMemberFunction(name);
                    if (func != null) owner = s;
                }
            }
            else
            {
                foreach (ScriptAutoCompleteData d in data.AsEnumerable().Reverse())
                {
                    func = d.FindFunction(name);
                    if (func != null) break;
                }
            }
            if (func == null) return null;

            // ConstructFunctionCalltipText
            var parameters = new List<string>();
            if (!string.IsNullOrWhiteSpace(func.ParamList))
            {
                foreach (string raw in func.ParamList.Split(','))
                {
                    string thisParam = raw.Trim();
                    if (thisParam.IndexOf('=') > 0)
                        thisParam = "optional " + thisParam.Substring(0, thisParam.IndexOf('=')).Trim();
                    parameters.Add(thisParam);
                }
            }
            string prefix = func.Type + " " + (owner != null ? owner.Name + "." : "") + func.FunctionName + "(";

            // ShowEnumForParameterIfAppropriate
            IReadOnlyList<string> enumValues = null;
            if (commas < parameters.Count)
            {
                string parameter = parameters[commas];
                if (parameter.StartsWith("optional ")) parameter = parameter.Substring(9);
                int space = parameter.IndexOf(' ');
                string typeName = space > 0 ? parameter.Substring(0, space) : parameter;
                foreach (ScriptAutoCompleteData d in data)
                {
                    ScriptEnum e = d.FindEnum(typeName);
                    if (e != null)
                    {
                        enumValues = e.EnumValues.Select(v => v.Name).ToList();
                        break;
                    }
                }
            }
            return new CallTip(prefix, parameters, commas, func.Description, enumValues);
        }

        /// <summary>Where a symbol is defined: the script and the character offset of its declaration.</summary>
        public sealed class Definition
        {
            public Definition(Script script, int offset, string symbol) { Script = script; Offset = offset; Symbol = symbol; }
            public Script Script { get; }
            public int Offset { get; }
            public string Symbol { get; }
            /// <summary>Declared by the engine's script API (agsdefns.sh) or generated by the editor.</summary>
            public bool IsBuiltIn => Script.FileName == "agsdefns.sh" || Script.FileName.StartsWith("_", StringComparison.Ordinal);
        }

        /// <summary>
        /// Go to Definition (upstream ScriptEditorBase.GoToDefinition): the declaration of the identifier at
        /// <paramref name="offset"/> — a struct member after "x." (its struct resolved like member completion),
        /// otherwise a function, variable, struct, enum or enum value. Script bodies are preferred to imports in
        /// headers; local variables are found in the text before the use. Null if nothing is found.
        /// </summary>
        public Definition FindDefinition(Script script, string text, int offset)
        {
            if (string.IsNullOrEmpty(text) || offset < 0 || offset > text.Length) return null;
            int start = offset, end = offset;
            while (start > 0 && (char.IsLetterOrDigit(text[start - 1]) || text[start - 1] == '_')) start--;
            while (end < text.Length && (char.IsLetterOrDigit(text[end]) || text[end] == '_')) end++;
            if (end <= start) return null;
            string memberName = text.Substring(start, end - start);

            Update(script);
            var data = Visible(script).ToList();
            string structName = null;
            if (start > 0 && text[start - 1] == '.')
            {
                Match m = Identifier.Match(text.Substring(0, start - 1));
                if (m.Success)
                {
                    string word = m.Value;
                    ScriptStruct type = FindStruct(data, word);
                    if (type == null)
                    {
                        string typeName = FindVariableType(data, word) ?? FindLocalVariableType(text, m.Index, word);
                        type = typeName == null ? null : FindStruct(data, typeName);
                    }
                    structName = type?.Name;
                }
            }

            // "all scripts!": every header (built-in API, generated, global variables, modules), then this script.
            var scripts = new List<Script> { _builtIn, _autoGenerated, _globalVariables };
            foreach (ScriptAndHeader module in _game.RootScriptFolder.AllItemsFlat)
                scripts.Add(module.Header);
            if (!scripts.Contains(script))
                scripts.Add(script);

            foreach (Script candidate in scripts)
            {
                if (!candidate.AutoCompleteData.Populated)
                    AutoComplete.ConstructCache(candidate, GetImportedHeaders(candidate));
                ScriptToken found = FindToken(candidate, data, structName, memberName);
                Script foundIn = candidate;
                if (found != null && candidate.IsHeader)
                {
                    // Always prefer the definition in the main script to the import in the header
                    Script mainScript = _game.RootScriptFolder.FindMatchingScriptOrHeader(candidate);
                    if (mainScript != null)
                    {
                        if (!mainScript.AutoCompleteData.Populated)
                            AutoComplete.ConstructCache(mainScript, GetImportedHeaders(mainScript));
                        ScriptToken inBody = FindToken(mainScript, data, structName, memberName);
                        if (inBody != null)
                        {
                            found = inBody;
                            foundIn = mainScript;
                        }
                    }
                }
                if (found != null)
                    return new Definition(foundIn, NameStart(foundIn.Text, found.StartsAtCharacterIndex, memberName),
                        structName == null ? memberName : structName + "." + memberName);
            }

            // local variable or parameter: its declaration before the use
            if (structName == null)
            {
                var decl = new Regex(@"\b[A-Za-z_]\w*\s*\*?\s*\b(" + Regex.Escape(memberName) + @")\b\s*[=;,)\[]");
                Match last = null;
                foreach (Match m in decl.Matches(text.Substring(0, start)))
                    last = m;
                if (last != null && !last.Value.StartsWith("return", StringComparison.Ordinal))
                    return new Definition(script, last.Groups[1].Index, memberName);
            }
            return null;
        }

        // The parser records the position where it was when it took the token (around the end of its name):
        // use the start of the name's last occurrence up to there.
        private static int NameStart(string text, int position, string name)
        {
            if (string.IsNullOrEmpty(text)) return 0;
            int from = Math.Clamp(position + name.Length, 0, text.Length - 1);
            int index = text.LastIndexOf(name, from, StringComparison.Ordinal);
            return index >= 0 ? index : Math.Clamp(position, 0, text.Length);
        }

        /// <summary>ScriptEditorBase.FindTokenInScript.</summary>
        private static ScriptToken FindToken(Script script, List<ScriptAutoCompleteData> data, string structName, string memberName)
        {
            ScriptAutoCompleteData d = script.AutoCompleteData;
            if (structName != null)
            {
                ScriptStruct struc = d.FindStruct(structName);
                if (struc != null)
                {
                    ScriptToken member = (ScriptToken)struc.FindMemberFunction(memberName) ?? struc.FindMemberVariable(memberName);
                    if (member != null) return member;
                }
                // extender functions / struct member implementations: "Struct::member"
                for (ScriptStruct s = FindStruct(data, structName); s != null; s = string.IsNullOrEmpty(s.ParentType) ? null : FindStruct(data, s.ParentType))
                {
                    ScriptFunction f = d.FindFunction(s.Name + "::" + memberName);
                    if (f != null) return f;
                }
                return null;
            }
            return (ScriptToken)d.FindFunction(memberName) ?? (ScriptToken)d.FindVariable(memberName) ?? (ScriptToken)d.FindStruct(memberName)
                ?? (ScriptToken)d.FindEnum(memberName) ?? (ScriptToken)d.FindEnumValue(memberName) ?? d.FindDefine(memberName);
        }

        private static ScriptAPIVersion? ParseApiVersion(string s)
        {
            return Enum.TryParse(s, out ScriptAPIVersion v) ? v : (ScriptAPIVersion?)null;
        }

        // ---- ScintillaWrapper.ParsePreviousExpression & co.: the type of "a.b[i].c" before a dot ----

        /// <summary>GetPreviousPathedExpression: words, dots and [] groups before <paramref name="end"/>.</summary>
        private static string GetPreviousPathedExpression(string text, int end)
        {
            int cursorPos = end - 1;
            bool started = false;
            while (cursorPos >= 0)
            {
                char c = text[cursorPos];
                if (c == ']')
                {
                    int depth = 1;
                    cursorPos--;
                    while (depth > 0 && cursorPos >= 0)
                    {
                        char check = text[cursorPos];
                        if (check == ']') depth++;
                        if (check == '[') depth--;
                        if (check == '\n' || check == '\r') return string.Empty;
                        cursorPos--;
                    }
                    started = true;
                }
                else if (c == '.' || c == '_' || char.IsLetterOrDigit(c))
                {
                    cursorPos--;
                    started = true;
                }
                else if (c == ' ' && !started)
                {
                    cursorPos--;
                }
                else
                {
                    break;
                }
                if (cursorPos < end - 200) return string.Empty; // probably invalid syntax
            }
            return text.Substring(cursorPos + 1, end - cursorPos - 1).Trim();
        }

        // ReadNextWord (unchanged logic)
        private static string ReadNextWord(ref string pathedExpression, out bool indexedAccess, out int dimAccess)
        {
            string thisWord = string.Empty;
            indexedAccess = false;
            dimAccess = 0;
            while (pathedExpression.Length > 0 && (char.IsLetterOrDigit(pathedExpression[0]) || pathedExpression[0] == '_'))
            {
                thisWord += pathedExpression[0];
                pathedExpression = pathedExpression.Substring(1);
            }
            pathedExpression = pathedExpression.TrimStart();
            while (pathedExpression.Length > 0 && pathedExpression[0] == '[')
            {
                indexedAccess = true;
                dimAccess++;
                int bracketDepth = 1;
                int cursorPos = 1;
                while (bracketDepth > 0 && cursorPos < pathedExpression.Length)
                {
                    char checkChar = pathedExpression[cursorPos];
                    if (checkChar == ']') bracketDepth--;
                    if (checkChar == '[') bracketDepth++;
                    cursorPos++;
                }
                pathedExpression = pathedExpression.Substring(cursorPos).TrimStart();
            }
            if (pathedExpression.Length > 0 && pathedExpression[0] == '.')
                pathedExpression = pathedExpression.Substring(1);
            return thisWord;
        }

        private static ScriptStruct ParsePreviousExpression(List<ScriptAutoCompleteData> data, string text, int dot, out bool staticAccess)
        {
            staticAccess = false;
            string pathedExpression = GetPreviousPathedExpression(text, dot);
            if (pathedExpression.Length == 0) return null;
            string thisWord = ReadNextWord(ref pathedExpression, out bool indexedAccess, out int dimAccess);
            ScriptStruct foundType = null;
            if (thisWord == "this")
            {
                foundType = FindStructOrNull(data, FindTypeForThis(text, dot));
            }
            else if (thisWord.Length > 0)
            {
                foundType = FindStruct(data, thisWord);
                if (foundType != null && foundType.FullDefinition)
                {
                    if (indexedAccess) return null; // element access of a type: bad syntax
                    staticAccess = true;
                }
                else
                {
                    foundType = null;
                    ScriptVariable var = FindGlobalVariable(data, thisWord);
                    if (var != null)
                        foundType = ProcessVariableAccess(data, var, indexedAccess, dimAccess);
                }
                if (foundType == null)
                {
                    string localType = FindLocalVariableType(text, dot - pathedExpression.Length, thisWord);
                    if (localType != null)
                    {
                        foundType = FindStructOrNull(data, localType);
                        if (foundType != null && indexedAccess && !string.IsNullOrEmpty(foundType.BaseType))
                            foundType = FindStructOrNull(data, foundType.BaseType);
                    }
                }
            }
            while (pathedExpression.Length > 0 && foundType != null)
            {
                thisWord = ReadNextWord(ref pathedExpression, out indexedAccess, out dimAccess);
                ScriptVariable memberVar = FindMemberVariable(data, foundType, thisWord);
                if (memberVar == null) return null;
                foundType = ProcessVariableAccess(data, memberVar, indexedAccess, dimAccess);
                staticAccess = false;
            }
            return foundType;
        }

        // ProcessVariableAccess (unchanged logic)
        private static ScriptStruct ProcessVariableAccess(List<ScriptAutoCompleteData> data, ScriptVariable var, bool indexedAccess, int accessDims)
        {
            if (indexedAccess && !var.IsArray && !var.IsIndexedAttribute)
                return null; // accessing element of non-array (and not indexed attrib), bad syntax...
            if (!indexedAccess && ((var.IsArray && !var.IsDynamicArray) || var.IsIndexedAttribute))
                return null; // accessing member of static array (or indexed attribute), no result
            ScriptStruct foundType = FindStructOrNull(data, var.Type);
            if (foundType == null)
                return null;
            if (var.IsDynamicArray && indexedAccess)
            {
                for (int i = 0; i < accessDims && foundType != null; ++i)
                    foundType = FindStructOrNull(data, foundType.BaseType);
            }
            return foundType;
        }

        /// <summary>FindMemberVariable, also in the parent types (struct extends).</summary>
        private static ScriptVariable FindMemberVariable(List<ScriptAutoCompleteData> data, ScriptStruct type, string name)
        {
            for (ScriptStruct s = type; s != null; s = string.IsNullOrEmpty(s.ParentType) ? null : FindStruct(data, s.ParentType))
            {
                ScriptVariable v = s.FindMemberVariable(name);
                if (v != null) return v;
            }
            return null;
        }

        private static ScriptVariable FindGlobalVariable(IEnumerable<ScriptAutoCompleteData> data, string name)
        {
            foreach (ScriptAutoCompleteData d in data.Reverse())
                foreach (ScriptVariable v in d.Variables)
                    if (v.VariableName == name)
                        return v;
            return null;
        }

        private static ScriptStruct FindStructOrNull(IEnumerable<ScriptAutoCompleteData> data, string name) =>
            string.IsNullOrEmpty(name) ? null : FindStruct(data, name);

        /// <summary>FindTypeForThis: the struct of the member or extender function the position is in.</summary>
        private static string FindTypeForThis(string text, int position)
        {
            string[] lines = text.Substring(0, position).Split('\n');
            for (int lineNumber = lines.Length - 1; lineNumber >= Math.Max(0, lines.Length - 500); lineNumber--)
            {
                string lineText = lines[lineNumber];
                int structNameEnd = lineText.IndexOf("::", StringComparison.Ordinal);
                if (structNameEnd >= 0)
                {
                    int structNameStart = structNameEnd - 1;
                    while (structNameStart >= 0 && (char.IsLetterOrDigit(lineText[structNameStart]) || lineText[structNameStart] == '_'))
                        structNameStart--;
                    structNameStart++;
                    return lineText.Substring(structNameStart, structNameEnd - structNameStart);
                }
                int extenderFunction = lineText.IndexOf("(this ", StringComparison.Ordinal);
                if (extenderFunction >= 0)
                {
                    Match m = Regex.Match(lineText.Substring(extenderFunction + 5), @"^\s*([A-Za-z_]\w*)");
                    return m.Success ? m.Groups[1].Value : string.Empty;
                }
                if (lineText.IndexOf("function ", StringComparison.Ordinal) >= 0)
                    break; // a function that isn't a struct member
            }
            return string.Empty;
        }

        private static ScriptStruct FindStruct(IEnumerable<ScriptAutoCompleteData> data, string name)
        {
            ScriptStruct draft = null;
            foreach (ScriptAutoCompleteData d in data)
            {
                foreach (ScriptStruct s in d.Structs)
                {
                    if (s.Name != name) continue;
                    if (s.FullDefinition) return s;
                    draft ??= s;
                }
            }
            return draft;
        }

        private static string FindVariableType(IEnumerable<ScriptAutoCompleteData> data, string name)
        {
            foreach (ScriptAutoCompleteData d in data.Reverse())
                foreach (ScriptVariable v in d.Variables)
                    if (v.VariableName == name)
                        return v.Type;
            return null;
        }

        // Local variables and parameters: the nearest "Type name" or "Type *name" declaration before the use.
        private static string FindLocalVariableType(string text, int before, string name)
        {
            var decl = new Regex(@"\b([A-Za-z_]\w*)\s*\*?\s*\b" + Regex.Escape(name) + @"\b\s*[=;,)\[]");
            Match last = null;
            foreach (Match m in decl.Matches(text.Substring(0, before)))
                last = m;
            if (last == null) return null;
            string type = last.Groups[1].Value;
            return type is "return" or "new" ? null : type;
        }
    }

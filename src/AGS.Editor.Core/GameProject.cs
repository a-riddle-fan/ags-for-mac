using System;
using System.Collections.Generic;
using System.IO;
using System.Text;
using System.Xml;
using AGS.Editor.Hosting;
using AGS.Types;

namespace AGS.Editor
{
    /// <summary>
    /// An open game project: loading and saving Game.agf (and Game.agf.user) the way the upstream editor
    /// does in AGSEditor.LoadGameFile/LoadUserDataFile/SaveGameFilesProcess/SaveUserDataFile and
    /// Tasks.LoadGameFromDisk.
    /// </summary>
    /// <remarks>
    /// Like upstream, the editor logic resolves project files relative to the current directory
    /// (e.g. Script.LoadFromDisk), so <see cref="Load"/> makes the game folder the current directory.
    /// Component sections ("Component" nodes) that no ported component handles yet are kept verbatim
    /// and written back unchanged, so no project data is lost.
    /// </remarks>
    public sealed class GameProject
    {
        // Constants from ags/Editor/AGS.Editor/AGSEditor.cs
        public const string GAME_FILE_NAME = "Game.agf";
        public const string BACKUP_EXTENSION = "bak";
        public const string USER_DATA_FILE_SUFFIX = ".user";
        public const string LOCK_FILE_NAME = "_OpenInEditor.lock";
        public const string SPRITE_FILE_NAME = "acsprset.spr";
        public const string LATEST_XML_VERSION = "3.0.3.2";
        public const int LATEST_XML_VERSION_INDEX = 3060316;
        public const string LATEST_USER_DATA_VERSION = "3.0.2.1";
        public const int LATEST_USER_DATA_XML_VERSION_INDEX = 3060313;
        private const string XML_ROOT_NODE_NAME = "AGSEditorDocument";
        private const string XML_USER_DATA_ROOT_NODE_NAME = "AGSEditorUserData";
        private const string XML_ATTRIBUTE_VERSION = "Version";
        private const string XML_ATTRIBUTE_VERSION_INDEX = "VersionIndex";
        private const string XML_ATTRIBUTE_EDITOR_VERSION = "EditorVersion";
        private const string XML_COMMENT = "DO NOT EDIT THIS FILE. It is automatically generated by the AGS Editor, changing it manually could break your game";

        private readonly IEditorHost _host;
        private readonly List<XmlElement> _componentNodes = new List<XmlElement>();
        private readonly List<XmlElement> _userDataComponentNodes = new List<XmlElement>();

        private GameProject(Game game, string directory, IEditorHost host)
        {
            Game = game;
            Directory = directory;
            _host = host;
        }

        public Game Game { get; }

        /// <summary>Absolute path of the game folder.</summary>
        public string Directory { get; }

        public string GameFilePath => Path.Combine(Directory, GAME_FILE_NAME);

        /// <summary>Names of component sections carried over verbatim, in file order.</summary>
        public IReadOnlyList<string> PreservedComponents => _componentNodes.ConvertAll(n => n.GetAttribute("Name"));

        /// <summary>Loads a Game.agf project; port of Tasks.LoadGameFromDisk for .agf files.</summary>
        public static GameProject Load(string gameFile, IEditorHost host)
        {
            if (host == null) throw new ArgumentNullException(nameof(host));
            AnsiEncoding.EnsureCodePagesRegistered();
            string fullPath = Path.GetFullPath(gameFile);
            string directory = Path.GetDirectoryName(fullPath);

            System.IO.Directory.SetCurrentDirectory(directory);

            var game = new Game();
            var project = new GameProject(game, directory, host);
            AGSColor.ColorMapper = new ColorMapper(() => game);

            project.LoadGameFile(fullPath);

            game.DirectoryPath = directory;
            new GameUpgrader(host).ApplyAfterLoad(game);
            project.CheckSpriteFile();
            PostLoadFixups(game);
            // FontsComponent.RefreshDataFromGame: ProjectFilename is not serialized, so it is derived on load.
            foreach (Font font in game.Fonts)
            {
                if (string.IsNullOrEmpty(font.ProjectFilename))
                    font.ProjectFilename = File.Exists(Path.Combine(directory, font.TTFFileName)) ? font.TTFFileName : font.WFNFileName;
            }
            SyncCustomPropertiesWithSchema(game);
            TypeConverterLists.Refresh(game);
            return project;
        }

        // AGSEditor.LoadGameFile
        private void LoadGameFile(string fileName)
        {
            if (File.Exists(LOCK_FILE_NAME))
                VerifyGameNotAlreadyOpenInAnotherEditor();

            XmlNode userData = null;
            if (File.Exists(fileName + USER_DATA_FILE_SUFFIX))
                userData = LoadUserDataFile(fileName + USER_DATA_FILE_SUFFIX);

            XmlDocument doc = new XmlDocument();
            doc.Load(fileName);
            if (doc.DocumentElement.Name != XML_ROOT_NODE_NAME)
            {
                throw new AGSEditorException("Invalid game data file. This is not a valid AGS game.");
            }
            string fileVersion = doc.DocumentElement.Attributes[XML_ATTRIBUTE_VERSION].InnerXml;
            if ((fileVersion != LATEST_XML_VERSION) &&
                (fileVersion != "3.0.1.1") &&
                (fileVersion != "3.0.2.1") &&
                (fileVersion != "3.0.2.2") &&
                (fileVersion != "3.0.3.1") &&
                (fileVersion != "2.80.1"))
            {
                throw new AGSEditorException("Game data file is from a newer version of AGS or an unsupported beta version. Please check the AGS website for a newer version of the editor.");
            }

            string gameSavedWithEditorVersion = null;
            XmlAttribute editorVersionNode = doc.DocumentElement.Attributes[XML_ATTRIBUTE_EDITOR_VERSION];
            if (editorVersionNode != null)
            {
                gameSavedWithEditorVersion = editorVersionNode.InnerText;
            }

            int? versionIndex = null;
            XmlAttribute versionIndexNode = doc.DocumentElement.Attributes[XML_ATTRIBUTE_VERSION_INDEX];
            if ((versionIndexNode == null) && (fileVersion == LATEST_XML_VERSION))
            {
                throw new AGSEditorException("Invalid format game data file");
            }
            else if (versionIndexNode != null)
            {
                versionIndex = Convert.ToInt32(versionIndexNode.InnerText);
                if (versionIndex == 5)
                {
                    throw new AGSEditorException("This game is from an unsupported beta version of AGS and cannot be loaded.");
                }
                if ((versionIndex < 1) || (versionIndex > LATEST_XML_VERSION_INDEX))
                {
                    throw new AGSEditorException("Game data file is from " +
                        ((gameSavedWithEditorVersion == null) ? "a newer version" : ("version " + gameSavedWithEditorVersion))
                        + " of AGS or an unsupported beta version. Please check the AGS website for a newer version of the editor.");
                }
            }

            Game.SavedXmlVersionIndex = versionIndex;
            Game.SavedXmlVersion = fileVersion;
            Game.SavedXmlEditorVersion = gameSavedWithEditorVersion;
            try
            {
                // Try to retrieve the xml encoding declaration, to be used as a fallback for older projects
                XmlDeclaration dec = doc.FirstChild as XmlDeclaration;
                Game.SavedXmlEncodingCodePage = Encoding.GetEncoding(dec.Encoding).CodePage;
            }
            catch (Exception) { }

            Game.FromXml(doc.DocumentElement);

            // Factory.Events.OnGameLoad: components read their "Component" sections. Keep them all.
            foreach (XmlNode node in doc.DocumentElement.SelectNodes("Component"))
                _componentNodes.Add((XmlElement)node.Clone());

            Game.WorkspaceState.FromXml(userData);
        }

        // AGSEditor.LoadUserDataFile
        private XmlNode LoadUserDataFile(string fileName)
        {
            XmlNode docNode = null;
            try
            {
                XmlDocument doc = new XmlDocument();
                doc.Load(fileName);
                if (doc.DocumentElement.Name != XML_USER_DATA_ROOT_NODE_NAME)
                {
                    throw new AGSEditorException("Invalid user data file. This is not a valid AGS user data file.");
                }
                string fileVersion = doc.DocumentElement.Attributes[XML_ATTRIBUTE_VERSION].InnerXml;
                if (fileVersion != LATEST_USER_DATA_VERSION)
                {
                    throw new AGSEditorException("User data file is from a newer version of AGS or an unsupported beta version. Please check the AGS website for a newer version of the editor.");
                }
                string userDataSavedWithEditorVersion = doc.DocumentElement.Attributes[XML_ATTRIBUTE_EDITOR_VERSION]?.InnerText;
                XmlAttribute versionIndexNode = doc.DocumentElement.Attributes[XML_ATTRIBUTE_VERSION_INDEX];
                if (versionIndexNode != null)
                {
                    int versionIndex = Convert.ToInt32(versionIndexNode.InnerText);
                    if ((versionIndex < 1) || (versionIndex > LATEST_USER_DATA_XML_VERSION_INDEX))
                    {
                        throw new AGSEditorException("This game's user data file is from " +
                            ((userDataSavedWithEditorVersion == null) ? "a newer version" : ("version " + userDataSavedWithEditorVersion))
                            + " of AGS or an unsupported beta version. Please check the AGS website for a newer version of the editor.");
                    }
                }
                docNode = doc.DocumentElement;
                foreach (XmlNode node in docNode.SelectNodes("Component"))
                    _userDataComponentNodes.Add((XmlElement)node.Clone());
            }
            catch (Exception ex)
            {
                _host.ShowMessage("Unable to read the user preferences file for this project. You may lose some of your Preferences settings.\n" + ex.Message, MessageSeverity.Warning);
            }
            return docNode;
        }

        private static void VerifyGameNotAlreadyOpenInAnotherEditor()
        {
            try
            {
                try
                {
                    File.Delete(LOCK_FILE_NAME);
                }
                catch (UnauthorizedAccessException)
                {
                    File.SetAttributes(LOCK_FILE_NAME, FileAttributes.Normal);
                    File.Delete(LOCK_FILE_NAME);
                }
            }
            catch
            {
                throw new AGSEditorException("Cannot load the game, because it is already open in another copy of the AGS Editor");
            }
        }

        // Tasks.InitSpritesAfterGameLoad: the interactive recovery (reimport / new sprite file) belongs to the UI.
        private void CheckSpriteFile()
        {
            if (!File.Exists(Path.Combine(Directory, SPRITE_FILE_NAME)))
            {
                _host.ShowMessage($"Spriteset file ({SPRITE_FILE_NAME}) was not found.", MessageSeverity.Warning);
            }
        }

        // Factory.Events.OnGamePostLoad handlers that change data: ApplicationController._events_GamePostLoad
        // and ScriptsComponent.Events_GamePostLoad (SettingsComponent's only sets UI color modes).
        private static void PostLoadFixups(Game game)
        {
            foreach (Sprite sprite in game.RootSpriteFolder.GetAllSpritesFromAllSubFolders())
                sprite.SourceFile = ProjectPaths.GetRelativeToBasePath(sprite.SourceFile, game.DirectoryPath);
            foreach (AGS.Types.Font font in game.Fonts)
                font.SourceFilename = ProjectPaths.GetRelativeToBasePath(font.SourceFilename, game.DirectoryPath);
            foreach (AudioClip audio in game.RootAudioClipFolder.GetAllAudioClipsFromAllSubFolders())
            {
                audio.SourceFileName = ProjectPaths.GetRelativeToBasePath(audio.SourceFileName, game.DirectoryPath);
                audio.CacheFileName = ProjectPaths.GetAudioCacheFileName(audio);
            }

            if (game.SavedXmlVersionIndex < 3060110)
            {
                // < 3060110 - SetRestartPoint() has to be added to Global Script's game_start,
                // emulate legacy behavior where its call was hardcoded in the engine.
                Script script = game.RootScriptFolder.GetScriptByFileName(Script.GLOBAL_SCRIPT_FILE_NAME, true);
                if (script != null)
                {
                    script.Text = ScriptGeneration.InsertFunction(script.Text, "game_start", "", "  SetRestartPoint();", amendExisting: true);
                }
            }
        }

        /// <summary>The Game.agf document as the editor writes it (also used for temporary tool inputs).</summary>
        /// <summary>
        /// CustomPropertiesComponent.SyncCustomPropertiesWithSchema (on load and before saving): values of
        /// characters and inventory items follow the schema (removed properties dropped, name case fixed).
        /// Rooms are synced when they are loaded.
        /// </summary>
        public static void SyncCustomPropertiesWithSchema(Game game)
        {
            foreach (var c in game.RootCharacterFolder.AllItemsFlat)
                c.Properties.SyncWithSchema();
            foreach (var i in game.RootInventoryItemFolder.AllItemsFlat)
                i.Properties.SyncWithSchema();
        }

        public string BuildGameXml()
        {
            Game game = Game;
            var sw = new StringWriter();
            var writer = new XmlTextWriter(sw) { Formatting = Formatting.Indented };
            writer.WriteProcessingInstruction("xml", "version=\"1.0\" encoding=\"" + EncodingNames.GetWebName(game.TextEncoding) + "\"");
            writer.WriteComment(XML_COMMENT);
            writer.WriteStartElement(XML_ROOT_NODE_NAME);
            writer.WriteAttributeString(XML_ATTRIBUTE_VERSION, LATEST_XML_VERSION);
            writer.WriteAttributeString(XML_ATTRIBUTE_VERSION_INDEX, LATEST_XML_VERSION_INDEX.ToString());
            writer.WriteAttributeString(XML_ATTRIBUTE_EDITOR_VERSION, AGS.Types.Version.AGS_EDITOR_VERSION);

            game.SavedXmlVersion = LATEST_XML_VERSION;
            game.SavedXmlVersionIndex = LATEST_XML_VERSION_INDEX;
            game.SavedXmlEncodingCodePage = game.TextEncoding.CodePage;
            game.ToXml(writer);

            // Factory.Events.OnSavingGame -> ComponentController.NotifySavingGame
            foreach (XmlElement node in _componentNodes)
                node.WriteTo(writer);

            writer.WriteEndElement();
            writer.Flush();
            string gameXml = sw.ToString();
            writer.Close();
            return gameXml;

        }

        /// <summary>
        /// Saves Game.agf (via a temp file, keeping the previous one as Game.agf.bak), Game.agf.user and
        /// modified scripts; port of AGSEditor.SaveGameFilesProcess for the project file itself.
        /// </summary>
        public void Save()
        {
            Game game = Game;
            SyncCustomPropertiesWithSchema(game); // CustomPropertiesComponent.BeforeSaveGame
            SaveUserDataFile();

            string gameXml = BuildGameXml();

            WriteMainGameFile(gameXml);

            foreach (ScriptAndHeader script in game.RootScriptFolder.AllItemsFlat)
            {
                script.Header.SaveToDisk();
                script.Script.SaveToDisk();
            }
            // Room scripts that were loaded for editing (upstream: each open script editor saves its script).
            foreach (IRoom room in game.RootRoomFolder.AllItemsFlat)
            {
                if (room is UnloadedRoom unloaded && unloaded.Script != null && unloaded.Script.Modified)
                    unloaded.Script.SaveToDisk();
            }
        }

        // AGSEditor.SaveUserDataFile
        private void SaveUserDataFile()
        {
            var sw = new StringWriter();
            var writer = new XmlTextWriter(sw) { Formatting = Formatting.Indented };
            writer.WriteProcessingInstruction("xml", "version=\"1.0\" encoding=\"utf-8\"");
            writer.WriteComment(XML_COMMENT);
            writer.WriteStartElement(XML_USER_DATA_ROOT_NODE_NAME);
            writer.WriteAttributeString(XML_ATTRIBUTE_VERSION, LATEST_USER_DATA_VERSION);
            writer.WriteAttributeString(XML_ATTRIBUTE_VERSION_INDEX, LATEST_USER_DATA_XML_VERSION_INDEX.ToString());
            writer.WriteAttributeString(XML_ATTRIBUTE_EDITOR_VERSION, AGS.Types.Version.AGS_EDITOR_VERSION);

            // Factory.Events.OnSavingUserData -> ComponentController.NotifySavingUserData
            foreach (XmlElement node in _userDataComponentNodes)
                node.WriteTo(writer);

            Game.WorkspaceState.ToXml(writer);

            writer.WriteEndElement();
            writer.Flush();

            try
            {
                File.WriteAllText(GameFilePath + USER_DATA_FILE_SUFFIX, sw.ToString(), AGS.Types.Utilities.UTF8);
            }
            catch (Exception ex) when (ex is UnauthorizedAccessException || ex is IOException)
            {
                _host.ShowMessage("Unable to write the user data file. Ensure that you have write access to the game folder, and that the file is not already open.\n" + ex.Message, MessageSeverity.Warning);
            }
        }

        // AGSEditor.WriteMainGameFile
        private void WriteMainGameFile(string fileContents)
        {
            // First save the game into a temp file (in the project folder, so the final move is atomic)
            string gameFile = GameFilePath;
            string tempFile = gameFile + ".tmp";
            File.WriteAllText(tempFile, fileContents, Game.TextEncoding);

            // Create a backup file, by moving previous game file into backup
            string backupFile = $"{gameFile}.{BACKUP_EXTENSION}";
            if (File.Exists(gameFile))
            {
                if (File.Exists(backupFile))
                    File.Delete(backupFile);
                File.Move(gameFile, backupFile);
            }

            // Finally move the saved temp game file into place
            File.Move(tempFile, gameFile);
        }
    }
}

using System;
using System.Diagnostics;
using System.IO;
using System.Linq;
using System.Text;
using System.Threading.Tasks;
using AGS.Editor.Build;
using AGS.Imaging;
using AGS.Native;
using AGS.Types;

namespace AGS.Editor.Core.Tests
{
    /// <summary>
    /// Every room of the reference game, checked against upstream's room tool (crmpak): the rooms the
    /// editor saves must look the same to upstream, and the room part of the editor's script header must
    /// match the header agsbuild generates for room scripts.
    /// Needs the tools from scripts/build-upstream-tools.sh (build/agstools).
    /// </summary>
    public class RoomUpstreamToolTests : IDisposable
    {
        private readonly string _dir = Path.Combine(Path.GetTempPath(), "ags4mac-crmpak-" + Guid.NewGuid().ToString("N"));

        public RoomUpstreamToolTests()
        {
            Directory.CreateDirectory(_dir);
            AnsiEncoding.EnsureCodePagesRegistered();
        }

        public void Dispose()
        {
            Directory.Delete(_dir, true);
        }

        public static TheoryData<int> RoomNumbers()
        {
            var data = new TheoryData<int>();
            foreach (int n in Enumerable.Range(1, 21)) data.Add(n);
            return data;
        }

        private static string RoomFile(int number) => Path.Combine(ReferenceGame.Directory, $"room{number}.crm");

        [Theory]
        [MemberData(nameof(RoomNumbers))]
        public void SavedRoomHasTheSameContentForCrmpak(int number)
        {
            string original = RoomFile(number);
            string saved = Path.Combine(_dir, $"room{number}.crm");
            using (NativeRoom native = NativeRoom.Load(original))
            {
                Room room = native.ToRoom(new UnloadedRoom(number), AnsiEncoding.Default);
                native.ApplyRoom(room, AnsiEncoding.Default);
                native.Save(saved);
            }

            // The reference rooms come from editor 3.6.0; saving writes the current room format (as the
            // Windows editor of this AGS version does), so the data blocks may grow (e.g. "v363_objects")
            // and the main block is compressed differently. What crmpak reads from them must not change.
            (string[] blocksBefore, string contentBefore) = CrmpakList(original);
            (string[] blocksAfter, string contentAfter) = CrmpakList(saved);
            Assert.Empty(blocksBefore.Except(blocksAfter));
            Assert.True(contentBefore == contentAfter, $"original:\n{contentBefore}\nsaved:\n{contentAfter}");

            int backgrounds = contentBefore.Split('\n').Count(l => l.TrimStart().StartsWith("background "));
            var images = Enumerable.Range(0, backgrounds).Select(i => $"back{i}")
                .Concat(new[] { "mask-hotspot", "mask-region", "mask-walkarea", "mask-walkbehind" });
            foreach (string content in images)
            {
                string a = Path.Combine(_dir, $"a-{number}-{content}.bmp"), b = Path.Combine(_dir, $"b-{number}-{content}.bmp");
                RunCrmpak("-e", original, content, a);
                RunCrmpak("-e", saved, content, b);
                Assert.True(File.ReadAllBytes(a).SequenceEqual(File.ReadAllBytes(b)), $"room {number}: {content} differs");
            }
        }

        [Theory]
        [MemberData(nameof(RoomNumbers))]
        public void RoomScriptHeaderMatchesCrmpak(int number)
        {
            string ash = Path.Combine(_dir, $"room{number}.ash");
            RunCrmpak("-e", RoomFile(number), "ash", ash);

            Room room;
            using (NativeRoom native = NativeRoom.Load(RoomFile(number)))
                room = native.ToRoom(new UnloadedRoom(number), AnsiEncoding.Default);
            // The room's part of _AutoGenerated.ash is what the header with the room adds to the one without.
            var game = new Game();
            string withoutRoom = new AutoGeneratedHeader().RegenerateScriptHeader(game, null).Text;
            string withRoom = new AutoGeneratedHeader().RegenerateScriptHeader(game, room).Text;
            Assert.StartsWith(withoutRoom, withRoom);

            Assert.Equal(Lines(File.ReadAllText(ash)), Lines(withRoom.Substring(withoutRoom.Length)));
        }

        private static string[] Lines(string text) =>
            text.Replace("\r\n", "\n").Split('\n', StringSplitOptions.RemoveEmptyEntries);

        // crmpak's listing: the data block names, and the content (images with size and depth, item counts,
        // script sizes) without the block table, which depends on the room format version.
        private static (string[] Blocks, string Content) CrmpakList(string room)
        {
            string[] lines = Lines(RunCrmpak("-l", room));
            string[] blocks = lines.SkipWhile(l => !l.StartsWith("------ Block ID")).Skip(1).TakeWhile(l => !l.StartsWith("-----"))
                .Select(l => l.Split('|')[0].Trim()).ToArray();
            Assert.NotEmpty(blocks);
            string content = string.Join("\n", lines.SkipWhile(l => !l.StartsWith("* ")));
            Assert.Contains("* Room backgrounds", content);
            return (blocks, content);
        }

        private static string RunCrmpak(params string[] args)
        {
            AgsBuildToolchain toolchain = AgsBuildToolchain.Locate(searchFrom: AppContext.BaseDirectory);
            Assert.True(toolchain != null, "agsbuild not found; run scripts/build-upstream-tools.sh");
            var psi = new ProcessStartInfo(Path.Combine(toolchain.ToolsDirectory, "crmpak"))
            {
                UseShellExecute = false,
                RedirectStandardOutput = true,
                RedirectStandardError = true,
            };
            foreach (string a in args) psi.ArgumentList.Add(a);
            using Process p = Process.Start(psi);
            Task<string> stderr = p.StandardError.ReadToEndAsync();
            string stdout = p.StandardOutput.ReadToEnd();
            p.WaitForExit();
            Assert.True(p.ExitCode == 0, $"crmpak {string.Join(' ', args)} failed ({p.ExitCode}): {stdout}{stderr.Result}");
            return stdout;
        }
    }
}

using System;
using System.IO;
using System.Linq;
using AGS.Editor.Hosting;
using AGS.Types;

namespace AGS.Editor.Core.Tests
{
    [Collection(CurrentDirectoryCollection.Name)]
    public class ScriptCompletionTests
    {
        private static (ScriptCompletion Completion, Script Global) Setup()
        {
            AGS.Editor.Build.KnownBuildTargets.RegisterAll();
            GameProject project = GameProject.Load(Path.Combine(ReferenceGame.Directory, "Game.agf"), new ConsoleEditorHost(TextWriter.Null));
            var completion = new ScriptCompletion(project.Game);
            Script global = project.Game.RootScriptFolder.GetScriptByFileName("GlobalScript.asc", true);
            completion.Update(global);
            return (completion, global);
        }

        private static string[] Members(ScriptCompletion c, Script script, string code)
        {
            string text = script.Text + "\nfunction ags4mac_test()\n{\n" + code;
            return c.GetMembers(script, text, text.Length).Select(i => i.Text).ToArray();
        }

        [Fact]
        public void MembersOfBuiltInAndGameObjects()
        {
            var (c, global) = Setup();

            string[] player = Members(c, global, "  player.");
            Assert.Contains("Say", player);
            Assert.Contains("Walk", player);
            Assert.Contains("x", player);
            // Legacy members (#ifndef STRICT) are hidden in object-based games, like upstream.
            Assert.DoesNotContain("activeinv", player);

            // cDave is declared in the generated header (_AutoGenerated.ash).
            Assert.Contains("Say", Members(c, global, "  cDave."));

            // Static members for type names.
            string[] game = Members(c, global, "  Game.");
            Assert.Contains("GetColorFromRGB", game);
            Assert.DoesNotContain("Say", game);

            // Local variables (pointer declarations).
            Assert.Contains("Graphic", Members(c, global, "  InventoryItem *item = inventory[1];\n  item."));
        }

        [Fact]
        public void MembersOfChainsArraysAndThis()
        {
            var (c, global) = Setup();
            // member chains (ScintillaWrapper.ParsePreviousExpression)
            string[] activeInv = Members(c, global, "  player.ActiveInventory.");
            Assert.Contains("Graphic", activeInv);
            Assert.DoesNotContain("Walk", activeInv);
            Assert.Contains("Say", Members(c, global, "  character[0]."));     // array element
            Assert.Contains("Graphic", Members(c, global, "  character[player.ID + 1].ActiveInventory."));
            Assert.Empty(Members(c, global, "  character."));                   // a static array itself has no members
            Assert.Contains("Say", Members(c, global, "  player . "[..^1]));      // a space before the dot is fine
            // "this" in an extender function
            string text = global.Text + "\nfunction ags4mac_ext(this Character*)\n{\n  this.";
            Assert.Contains("Walk", c.GetMembers(global, text, text.Length).Select(i => i.Text));
            // a chain through something that isn't a variable gives nothing
            Assert.Empty(Members(c, global, "  player.Say."));
        }

        [Fact]
        public void GlobalIdentifiers()
        {
            var (c, global) = Setup();
            var items = c.GetGlobal(global, "Disp");
            Assert.Contains(items, i => i.Text == "Display" && i.Kind == CompletionKind.Function && i.Description.Contains("Display("));
            Assert.Contains(c.GetGlobal(global, "eDir"), i => i.Kind == CompletionKind.EnumValue);
            Assert.Contains(c.GetGlobal(global, "whi"), i => i.Text == "while" && i.Kind == CompletionKind.Keyword);
        }
    }
}
